#!/usr/bin/env python3
"""
Build single-file, self-contained copies of the Legislative Scenario Explorer.

The explorer is a multi-file application, which is right for maintenance and
wrong for distribution: a legislator or committee staffer who is emailed
index.html on its own gets a blank page, because the stylesheet, the engine and
the generated data all live in sibling directories. This script inlines every
local dependency into one HTML file per page, so each can be emailed, dropped on
a shared drive, or opened from a USB stick with no server and no build step.

    python3 build_standalone.py          # writes dist/

Nothing is recomputed here and no number is touched. This is a packaging step:
the stylesheet, the scripts and the generated data files are inlined byte for
byte, so a standalone build is the same model as the directory it came from.

Illustrative policy-analysis model. Not an actuarial certification, not the VRS
Board impact statement required under Va. Code § 30-19.1:7, and not a General
Assembly fiscal impact statement.

Prepared by Policy Development Team using legal, policy, and financial analysis
tools, pending review by veterans' legal counsel.
"""
from __future__ import annotations

import os
import re
import sys
import base64

HERE = os.path.dirname(os.path.abspath(__file__))
DIST = os.path.join(HERE, "dist")

# Cross-links have to be rewritten, because the standalone files sit alongside
# each other under different names.
RENAME = {
    "index.html": "explorer-standalone.html",
    "methodology.html": "methodology-standalone.html",
    "walkthrough.html": "walkthrough-standalone.html",
}

# Cross-page navigation inside a single file.
#
# Two problems to solve at once. First, a page may link to a sibling more than
# once — walkthrough.html links to the dashboard from its masthead, its sidebar
# and its closing section — and substituting a 540 KB data URL at each one
# tripled the output. So each sibling payload is defined exactly ONCE and the
# links carry a key instead. Second, browsers block top-level navigation to a
# data: URL, so a substituted data URL would have produced a link that silently
# did nothing; the payload is therefore turned into a Blob URL at click time,
# which is permitted. The listener is delegated from the document because some
# links — the walk-through drawer's "open as its own page" — are created after
# this script runs.
XPAGE_LOADER = """
<script>
(function () {
  'use strict';
  var P = __PAYLOADS__;
  function blobUrl(key) {
    var e = P[key];
    if (e.url) return e.url;
    var bin = atob(e.b64), n = bin.length, bytes = new Uint8Array(n);
    for (var i = 0; i < n; i++) bytes[i] = bin.charCodeAt(i);
    e.url = URL.createObjectURL(new Blob([bytes], { type: 'text/html' }));
    return e.url;
  }
  document.addEventListener('click', function (ev) {
    var el = ev.target.closest && ev.target.closest('[data-xpage]');
    if (!el) return;
    var key = el.getAttribute('data-xpage');
    if (!P[key]) return;
    ev.preventDefault();
    window.location.href = blobUrl(key);
  });
})();
</script>
"""

BANNER = (
    "<!-- Single-file build. Generated by build_standalone.py from the "
    "explorer/ directory; do not edit by hand. Illustrative policy-analysis "
    "model: not an actuarial certification, not the VRS Board impact statement "
    "required under Va. Code 30-19.1:7, and not a General Assembly fiscal "
    "impact statement. -->\n"
)


def read(rel: str) -> str:
    with open(os.path.join(HERE, rel), "r", encoding="utf-8") as fh:
        return fh.read()


def _js_key(name: str) -> str:
    return '"%s"' % name.replace('"', '\\"')


def guard(text: str) -> str:
    """Stop an inlined payload from closing its own container element.

    None of the current sources contain the sequence, but a future edit to a
    note or a glossary entry could, and the failure mode is a silently truncated
    page rather than an error.
    """
    return text.replace("</script", "<\\/script").replace("</style", "<\\/style")


def inline(page: str, embedded_pages: dict[str, str] | None = None,
           disable_cross_links: bool = False) -> tuple[str, list[str]]:
    html = read(page)
    inlined: list[str] = []

    def css(m: re.Match) -> str:
        href = m.group(1)
        inlined.append(href)
        return "<style>\n" + guard(read(href)) + "\n</style>"

    def js(m: re.Match) -> str:
        src = m.group(1)
        inlined.append(src)
        return "<script>\n" + guard(read(src)) + "\n</script>"

    html = re.sub(
        r'<link[^>]+rel="stylesheet"[^>]+href="([^":]+)"[^>]*>', css, html)
    html = re.sub(r'<script src="([^":]+)"></script>', js, html)

    for old, new in RENAME.items():
        if disable_cross_links:
            # A title tooltip never appears on a touch device, and a reader who
            # arrived here through a blob: URL has no bookmarkable address to
            # return to. The route back is the browser's Back button, so say so
            # in visible text rather than in an attribute. MOO-271 finding m-04.
            html = html.replace(
                'href="%s"' % old,
                'href="#" class="xlink-disabled" title="Cross-page navigation is '
                'disabled in this embedded copy — use your browser\'s Back button '
                'to return to the walk-through"')
        elif embedded_pages and old in embedded_pages:
            html = html.replace('href="%s"' % old,
                                'href="#" data-xpage="%s"' % old)
        else:
            html = html.replace('href="%s"' % old, 'href="%s"' % new)

    if disable_cross_links:
        # Visible, not a tooltip. This copy is reached through a blob: URL that
        # cannot be bookmarked or re-shared, and its own cross-links are dead,
        # so the only route onward is Back. MOO-271 finding m-04.
        note = (
            '<div class="disclaimer print-required" style="border-color:var(--axis);'
            'background:var(--surface-2)">'
            '<strong>Embedded copy.</strong> You reached this page from the guided '
            'walk-through. Its own Methodology and walk-through links are disabled '
            'here, and this address cannot be bookmarked &mdash; use your '
            'browser&rsquo;s <strong>Back</strong> button to return to the '
            'walk-through.</div>'
        )
        at = html.find("<div class=\"disclaimer")
        if at < 0:
            at = html.find("</header>")
            if at < 0:
                raise SystemExit(
                    "%s has nowhere to put the embedded-copy note" % page)
            at += len("</header>")
        html = html[:at] + note + html[at:]

    if embedded_pages and not disable_cross_links:
        payloads = ",".join(
            '%s:{b64:"%s"}' % (_js_key(k), v) for k, v in sorted(embedded_pages.items()))
        loader = XPAGE_LOADER.replace("__PAYLOADS__", "{" + payloads + "}")
        # The LAST </body> only. ui.js builds the downloadable handout as a
        # string literal that contains both "<body>" and "</body>", so a
        # first-match replace injects the loader into the middle of that
        # literal and breaks the whole presentation layer.
        at = html.rfind("</body>")
        if at < 0:
            raise SystemExit("%s has no </body> to append the loader to" % page)
        html = html[:at] + loader + html[at:]

    # Anything still pointing at a local file would be a broken reference in a
    # file emailed on its own, so fail loudly rather than ship one.
    leftover = [
        u for u in re.findall(r'(?:src|href)="([^"#]+)"', html)
        if not u.startswith(("http:", "https:", "mailto:", "data:"))
        and u not in RENAME.values()
    ]
    if leftover:
        raise SystemExit(
            "%s still references local files after inlining: %s"
            % (page, ", ".join(sorted(set(leftover)))))

    return BANNER + html, inlined


def main() -> int:
    os.makedirs(DIST, exist_ok=True)
    total = 0
    # Each sibling page is embedded once as a data URL with its own cross-links
    # disabled, which bounds the nesting: an embedded copy never embeds another.
    embedded_once = {
        p: base64.b64encode(
            inline(p, disable_cross_links=True)[0].encode("utf-8")).decode("ascii")
        for p in RENAME
    }
    for page, out_name in RENAME.items():
        links = {p: u for p, u in embedded_once.items() if p != page}
        html, inlined = inline(page, embedded_pages=links)
        out = os.path.join(DIST, out_name)
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(html)
        size = os.path.getsize(out) / 1024.0
        total += size
        print("  %-32s %7.0f KB   inlined %d file(s): %s"
              % (out_name, size, len(inlined), ", ".join(inlined)))
    print("  %-32s %7.0f KB   in %s" % ("total", total, DIST))
    return 0


if __name__ == "__main__":
    sys.exit(main())
