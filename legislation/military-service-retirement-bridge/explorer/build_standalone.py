#!/usr/bin/env python3
"""
Build single-file, self-contained copies of the Legislative Scenario Explorer.

The explorer is a multi-file application, which is right for maintenance and
wrong for distribution: a legislator or committee staffer who is emailed
index.html on its own gets a blank page, because the stylesheet, the engine and
the generated data all live in sibling directories. This script inlines every
local dependency into one HTML file per page, so each can be emailed, dropped on
a shared drive, or opened from a USB stick with no server and no build step.

    python3 build_standalone.py          # writes dist/

Nothing is recomputed here and no number is touched. This is a packaging step:
the stylesheet, the scripts and the generated data files are inlined byte for
byte, so a standalone build is the same model as the directory it came from.

Illustrative policy-analysis model. Not an actuarial certification, not the VRS
Board impact statement required under Va. Code § 30-19.1:7, and not a General
Assembly fiscal impact statement.

Prepared by Policy Development Team using legal, policy, and financial analysis
tools, pending review by veterans' legal counsel.
"""
from __future__ import annotations

import os
import re
import sys
import base64

HERE = os.path.dirname(os.path.abspath(__file__))
DIST = os.path.join(HERE, "dist")

# Cross-links have to be rewritten, because the standalone files sit alongside
# each other under different names.
RENAME = {
    "index.html": "explorer-standalone.html",
    "methodology.html": "methodology-standalone.html",
}

BANNER = (
    "<!-- Single-file build. Generated by build_standalone.py from the "
    "explorer/ directory; do not edit by hand. Illustrative policy-analysis "
    "model: not an actuarial certification, not the VRS Board impact statement "
    "required under Va. Code 30-19.1:7, and not a General Assembly fiscal "
    "impact statement. -->\n"
)


def read(rel: str) -> str:
    with open(os.path.join(HERE, rel), "r", encoding="utf-8") as fh:
        return fh.read()


def guard(text: str) -> str:
    """Stop an inlined payload from closing its own container element.

    None of the current sources contain the sequence, but a future edit to a
    note or a glossary entry could, and the failure mode is a silently truncated
    page rather than an error.
    """
    return text.replace("</script", "<\\/script").replace("</style", "<\\/style")


def inline(page: str, embedded_links: dict[str, str] | None = None,
           disable_cross_links: bool = False) -> tuple[str, list[str]]:
    html = read(page)
    inlined: list[str] = []

    def css(m: re.Match) -> str:
        href = m.group(1)
        inlined.append(href)
        return "<style>\n" + guard(read(href)) + "\n</style>"

    def js(m: re.Match) -> str:
        src = m.group(1)
        inlined.append(src)
        return "<script>\n" + guard(read(src)) + "\n</script>"

    html = re.sub(
        r'<link[^>]+rel="stylesheet"[^>]+href="([^":]+)"[^>]*>', css, html)
    html = re.sub(r'<script src="([^":]+)"></script>', js, html)

    for old, new in RENAME.items():
        if disable_cross_links:
            html = html.replace('href="%s"' % old,
                                'href="#" title="Cross-page navigation is disabled in this embedded copy"')
        elif embedded_links and old in embedded_links:
            html = html.replace('href="%s"' % old,
                                'href="%s"' % embedded_links[old])
        else:
            html = html.replace('href="%s"' % old, 'href="%s"' % new)

    # Anything still pointing at a local file would be a broken reference in a
    # file emailed on its own, so fail loudly rather than ship one.
    leftover = [
        u for u in re.findall(r'(?:src|href)="([^"#]+)"', html)
        if not u.startswith(("http:", "https:", "mailto:", "data:"))
        and u not in RENAME.values()
    ]
    if leftover:
        raise SystemExit(
            "%s still references local files after inlining: %s"
            % (page, ", ".join(sorted(set(leftover)))))

    return BANNER + html, inlined


def main() -> int:
    os.makedirs(DIST, exist_ok=True)
    total = 0
    for page, out_name in RENAME.items():
        other_page = next(p for p in RENAME if p != page)
        linked_html, _ = inline(other_page, disable_cross_links=True)
        linked_data = "data:text/html;charset=utf-8;base64," + base64.b64encode(
            linked_html.encode("utf-8")).decode("ascii")
        html, inlined = inline(page, embedded_links={other_page: linked_data})
        out = os.path.join(DIST, out_name)
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(html)
        size = os.path.getsize(out) / 1024.0
        total += size
        print("  %-32s %7.0f KB   inlined %d file(s): %s"
              % (out_name, size, len(inlined), ", ".join(inlined)))
    print("  %-32s %7.0f KB   in %s" % ("total", total, DIST))
    return 0


if __name__ == "__main__":
    sys.exit(main())
